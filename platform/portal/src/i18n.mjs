/** Normalisér et sprogtag; ukendte sprog falder tilbage til dansk. */
export function normalizeLang(value) {
  if (typeof value !== "string") return DEFAULT_LANGUAGE;
  const base = value.trim().toLowerCase().split(/[-_]/)[0];
  return LANGUAGES.includes(base) ? base : DEFAULT_LANGUAGE;
}

/** Slå en tekst op og indsæt `{param}`-værdier. Ukendt nøgle returneres som den er. */
export function t(lang, key, params = {}) {
  const language = normalizeLang(lang);
  const template = MESSAGES[language]?.[key] ?? MESSAGES[DEFAULT_LANGUAGE]?.[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (params[name] === undefined ? `{${name}}` : String(params[name])));
}

/** Alle nøgler der findes på alle sprog (bruges af en dækningstest). */
export function messageKeys() {
  return [...new Set(Object.values(MESSAGES).flatMap((table) => Object.keys(table)))].sort();
}
