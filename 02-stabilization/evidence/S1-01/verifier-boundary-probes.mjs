import {mkdtempSync,mkdirSync,writeFileSync,readFileSync,existsSync,symlinkSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
const repo=resolve(process.argv[2]);
const output=resolve(process.argv[3]);
mkdirSync(output,{recursive:true});
const sandbox=mkdtempSync(join(output,'boundary-fixture-'));
const workspace=join(sandbox,'workspace');
const outside=join(sandbox,'outside-workspace');
mkdirSync(join(workspace,'00-core'),{recursive:true});
mkdirSync(join(workspace,'01-step1/output/dkc-001/deliverable'),{recursive:true});
mkdirSync(outside);
writeFileSync(join(workspace,'00-core/base.txt'),'BASE-UNCHANGED\n');
writeFileSync(join(workspace,'01-step1/output/dkc-001/deliverable/overlay.txt'),'FIXTURE\n');
const stack={schema:'dkc-overlay-stack/v1',tip:'dkc-001',base:{path:'00-core'},overlaysRoot:'01-step1/output',verifyApplyScripts:false,overlays:{'dkc-001':{predecessor:null}}};
writeFileSync(join(workspace,'stack.json'),JSON.stringify(stack));
const run=target=>{
 const p=spawnSync(process.execPath,[join(repo,'tools/assemble-platform.mjs'),'--workspace',workspace,'--stack',join(workspace,'stack.json'),'--target',target,'--json'],{encoding:'utf8',timeout:60000});
 return {exitCode:p.status,stdout:p.stdout,stderr:p.stderr,error:p.error?.message};
};
const records=[];
records.push({probe:'control_literal_parent_escape',...run('../literal-escape'),created:existsSync(join(sandbox,'literal-escape'))});
const linkType=process.platform==='win32'?'junction':'dir';
symlinkSync(outside,join(workspace,'alias-outside'),linkType);
records.push({probe:'missing_target_below_outside_symlink_parent',...run('alias-outside/new-platform'),outsideFileCreated:existsSync(join(outside,'new-platform/base.txt'))});
symlinkSync(join(workspace,'00-core'),join(workspace,'alias-input'),linkType);
records.push({probe:'missing_target_below_reserved_input_alias',...run('alias-input/new-platform'),historicalInputDirectoryModified:existsSync(join(workspace,'00-core/new-platform/overlay.txt'))});
const report={sourceCommit:'19407f6d6d741f69e049d27729a8f987b47aff71',platform:process.platform,node:process.version,scope:'Disposable verifier-owned fixture only; no writes outside fixture root',records};
writeFileSync(join(output,'boundary-probes.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
